package com.lightingai.app;

import org.junit.Test;
import static org.junit.Assert.*;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.io.File;
import java.util.Arrays;
import java.util.Base64;
import java.util.concurrent.CancellationException;
import java.security.GeneralSecurityException;

public final class SceneBackupCryptoTest {
    // Public, artificial test credentials only. Never used by production code.
    private static final char[] PASSWORD = "synthetic-password-Ž-2026".toCharArray();
    private static final byte[] PLAIN = "{\"synthetic\":\"Scena Ž ć — 42\"}".getBytes(StandardCharsets.UTF_8);
    @Test public void independentNodeFixtureOpensWithUnicodePassword() throws Exception {
        // Generated by the existing offline Node recovery suite before Gradle runs in CI.
        File fixture = new File("build/scene-backup-interop.txt");
        if (!fixture.isFile()) fixture = new File("app/build/scene-backup-interop.txt");
        byte[] file = Files.readAllBytes(fixture.toPath());
        assertArrayEquals(PLAIN, SceneBackupCrypto.decrypt(Base64.getDecoder().decode(new String(file, StandardCharsets.US_ASCII).trim()), PASSWORD));
    }
    @Test public void roundTripHasFreshSaltAndNonceAndNoPlaintext() throws Exception {
        byte[] first = SceneBackupCrypto.encrypt(PLAIN, PASSWORD);
        byte[] second = SceneBackupCrypto.encrypt(PLAIN, PASSWORD);
        assertFalse(Arrays.equals(first, second));
        assertFalse(Arrays.equals(Arrays.copyOfRange(first,10,42),Arrays.copyOfRange(second,10,42)));
        assertFalse(Arrays.equals(Arrays.copyOfRange(first,42,54),Arrays.copyOfRange(second,42,54)));
        assertArrayEquals(PLAIN, SceneBackupCrypto.decrypt(first,PASSWORD));
        assertArrayEquals(PLAIN, SceneBackupCrypto.decrypt(second,PASSWORD));
        assertFalse(new String(first,StandardCharsets.ISO_8859_1).contains("synthetic"));
    }
    @Test public void wrongPasswordAndModifiedHeaderCiphertextOrTagAreRejected() throws Exception {
        byte[] encoded=SceneBackupCrypto.encrypt(PLAIN,PASSWORD);
        assertThrows(GeneralSecurityException.class,()->SceneBackupCrypto.decrypt(encoded,"wrong-synthetic-password".toCharArray()));
        for(int offset:new int[]{10,42,54,encoded.length-1}){
            byte[] bad=encoded.clone();bad[offset]^=1;
            assertThrows(GeneralSecurityException.class,()->SceneBackupCrypto.decrypt(bad,PASSWORD));
        }
        byte[] version=encoded.clone();version[5]=2;
        assertThrows(IllegalArgumentException.class,()->SceneBackupCrypto.decrypt(version,PASSWORD));
        byte[] cost=encoded.clone();cost[9]^=1;
        assertThrows(IllegalArgumentException.class,()->SceneBackupCrypto.decrypt(cost,PASSWORD));
        assertThrows(IllegalArgumentException.class,()->SceneBackupCrypto.decrypt(new byte[53],PASSWORD));
    }
    @Test public void interruptionAndInputBoundsFailClosed() throws Exception {
        Thread.currentThread().interrupt();
        try{assertThrows(CancellationException.class,()->SceneBackupCrypto.encrypt(PLAIN,PASSWORD));}
        finally{Thread.interrupted();}
        assertThrows(IllegalArgumentException.class,()->SceneBackupCrypto.encrypt(PLAIN,"short".toCharArray()));
        assertThrows(IllegalArgumentException.class,()->SceneBackupCrypto.encrypt(new byte[SceneBackupCrypto.MAX_PLAIN_BYTES+1],PASSWORD));
    }
}
